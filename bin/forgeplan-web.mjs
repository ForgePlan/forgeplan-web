#!/usr/bin/env node
import { spawn, spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, "..");
const DIST_DIR = join(PKG_ROOT, "dist");

const argv = process.argv.slice(2);
const positional = argv.filter((a) => !a.startsWith("-"));
const flags = new Set(argv.filter((a) => a.startsWith("-")));

const cmd = positional[0] ?? "init";
const FORCE = flags.has("--force");
const QUIET = flags.has("-q") || flags.has("--quiet");
const SKIP_GITIGNORE = flags.has("--no-gitignore");

function log(line) {
  if (!QUIET) process.stdout.write(line + "\n");
}

function fail(line, code = 1) {
  process.stderr.write(`forgeplan-web: ${line}\n`);
  process.exit(code);
}

function copyDir(src, dest) {
  if (!existsSync(src)) {
    fail(
      `pre-built artifact missing at ${src}.\n` +
        `       This usually means the npm package was published without a build. ` +
        `Reinstall, or build from source via \`npm run build\`.`,
    );
  }
  if (existsSync(dest) && !FORCE) {
    cpSync(src, dest, {
      recursive: true,
      dereference: false,
      force: false,
      errorOnExist: false,
    });
  } else {
    mkdirSync(dest, { recursive: true });
    cpSync(src, dest, { recursive: true, dereference: false, force: true });
  }
}

function ensureForgeplanWorkspace(cwd) {
  const fpDir = join(cwd, ".forgeplan");
  if (!existsSync(fpDir)) {
    fail(
      `no .forgeplan/ directory found in ${cwd}.\n` +
        `       Run \`forgeplan init -y\` here first, then re-run \`npx @forgeplan/web init\`.`,
    );
  }
}

function ensureForgeplanBinary() {
  // Windows: `forgeplan` resolves to forgeplan.cmd (npm/scoop install).
  // Node spawnSync can't invoke .cmd without shell:true — fails with
  // status=null and the error mimics "binary missing", confusing users.
  const probe = spawnSync("forgeplan", ["--version"], {
    stdio: "ignore",
    shell: process.platform === "win32",
  });
  if (probe.status !== 0) {
    fail(
      `\`forgeplan\` binary is not on PATH.\n` +
        `       Install it from https://github.com/ForgePlan/forgeplan and re-run.`,
    );
  }
}

function ensureGitignore(cwd) {
  if (SKIP_GITIGNORE) return;

  const path = join(cwd, ".gitignore");
  const ENTRY = ".forgeplan-web/";
  const COMMENT = "# generated by @forgeplan/web init";
  const ENTRY_RE = /^[ \t]*\.forgeplan-web\/?[ \t]*$/m;

  if (!existsSync(path)) {
    writeFileSync(path, `${COMMENT}\n${ENTRY}\n`);
    log(`→ created .gitignore (added ${ENTRY})`);
    return;
  }

  const content = readFileSync(path, "utf8");
  if (ENTRY_RE.test(content)) {
    return;
  }

  const sep = content.length === 0 || content.endsWith("\n") ? "" : "\n";
  writeFileSync(path, `${content}${sep}\n${COMMENT}\n${ENTRY}\n`);
  log(`→ appended ${ENTRY} to .gitignore`);
}

function readWorkspaceRoot(target) {
  const cfgPath = join(target, "forgeplan-web.json");
  if (!existsSync(cfgPath)) return null;
  try {
    const cfg = JSON.parse(readFileSync(cfgPath, "utf8"));
    return cfg.workspaceRoot ?? null;
  } catch {
    return null;
  }
}

function init() {
  const cwd = process.cwd();
  ensureForgeplanWorkspace(cwd);
  ensureForgeplanBinary();

  const target = join(cwd, ".forgeplan-web");
  const fresh = !existsSync(target);
  log(fresh ? `→ creating ${target}` : `→ updating ${target}`);
  copyDir(DIST_DIR, target);

  const cfg = {
    workspaceRoot: cwd,
    createdAt: new Date().toISOString(),
  };
  writeFileSync(
    join(target, "forgeplan-web.json"),
    JSON.stringify(cfg, null, 2) + "\n",
  );

  ensureGitignore(cwd);

  log("");
  log("✓ ready (no install needed)");
  log("  npx @forgeplan/web start");
  log("  # or: node .forgeplan-web/index.js");
}

function start() {
  const cwd = process.cwd();
  const target = join(cwd, ".forgeplan-web");

  if (!existsSync(target) || !existsSync(join(target, "index.js"))) {
    fail(
      `no scaffolded server at ${target}.\n` +
        `       Run \`npx @forgeplan/web init\` first.`,
    );
  }

  const workspaceRoot = readWorkspaceRoot(target) ?? cwd;
  const env = {
    ...process.env,
    PORT: process.env.PORT ?? "5174",
    HOST: process.env.HOST ?? "127.0.0.1",
    FORGEPLAN_CWD: process.env.FORGEPLAN_CWD ?? workspaceRoot,
  };

  log(`→ starting forgeplan-web on http://${env.HOST}:${env.PORT}`);
  log(`  workspace: ${env.FORGEPLAN_CWD}`);

  const child = spawn(process.execPath, ["index.js"], {
    cwd: target,
    env,
    stdio: "inherit",
  });

  const forward = (sig) => {
    if (!child.killed) child.kill(sig);
  };
  process.on("SIGINT", () => forward("SIGINT"));
  process.on("SIGTERM", () => forward("SIGTERM"));

  child.on("exit", (code, signal) => {
    if (signal) process.exit(0);
    process.exit(code ?? 0);
  });
}

function help() {
  log(`@forgeplan/web — interactive realtime map for a Forgeplan workspace

Usage:
  npx @forgeplan/web init [-y] [--force] [--no-gitignore]
  npx @forgeplan/web start
  npx @forgeplan/web help

Commands:
  init    Copy the pre-built SvelteKit app to ./.forgeplan-web/ and
          append \`.forgeplan-web/\` to ./.gitignore (idempotent).
          --force          overwrite files that already exist
          --no-gitignore   do not touch ./.gitignore
          -y               accepted for compatibility (init is non-interactive)

  start   Run the SvelteKit server from ./.forgeplan-web/.
          Reads PORT (default 5174), HOST (default 127.0.0.1),
          FORGEPLAN_CWD (default: workspace recorded by init),
          FORGEPLAN_BIN (default: \`forgeplan\` from PATH).

The init command requires:
  - a .forgeplan/ workspace in the current directory
  - the \`forgeplan\` CLI on PATH

No npm install runs at user side: the package ships a pre-built artifact.
`);
}

switch (cmd) {
  case "init":
    init();
    break;
  case "start":
  case "serve":
  case "run":
    start();
    break;
  case "help":
  case "-h":
  case "--help":
    help();
    break;
  default:
    fail(`unknown command \`${cmd}\`. Try \`npx @forgeplan/web help\`.`);
}
