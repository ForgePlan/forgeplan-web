import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export function ensureGitignore({ cwd, skip = false, log = () => {} }) {
  if (skip) return;

  const path = join(cwd, ".gitignore");
  const ENTRY = ".forgeplan-web/";
  const COMMENT = "# generated by @forgeplan/web init";
  const ENTRY_RE = /^[ \t]*\.forgeplan-web\/?[ \t]*$/m;

  if (!existsSync(path)) {
    writeFileSync(path, `${COMMENT}\n${ENTRY}\n`);
    log(`→ created .gitignore (added ${ENTRY})`);
    return;
  }

  const content = readFileSync(path, "utf8");
  if (ENTRY_RE.test(content)) {
    return;
  }

  const sep = content.length === 0 || content.endsWith("\n") ? "" : "\n";
  writeFileSync(path, `${content}${sep}\n${COMMENT}\n${ENTRY}\n`);
  log(`→ appended ${ENTRY} to .gitignore`);
}
